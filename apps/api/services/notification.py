"""The Notification Service: the one place a notification is created.

``16-notifications.md`` asks for a *"centralized Notification Service"* that
subscribes to domain events, creates notifications, delivers them, marks them
read, and manages preferences — and requires that it *"remain independent from
business modules"*. This module is that service. The independence is a property
of the dependency graph rather than a convention: it holds a repository, an
:class:`~services.events.EventPublisher`, and a metrics recorder, and **not one
business service**. There is no path from here to a case, a document, or a
report that is not a read through :mod:`services.notification_recipients`.

The reverse direction is what actually matters, and it is stronger: **no business
module imports this file.** They publish domain events to a dispatcher that knows
no consumers; :mod:`services.notification_events` is registered on that
dispatcher in :mod:`core.lifespan`, one line beside the WebSocket manager. So
``code-standards.md``'s *"all notifications must be generated by the Notification
Service"* and the spec's *"business logic should never create notifications
directly"* are both true because there is no function a business module could
call, not because nobody has called one.

**Delivery goes back onto the event channel, and never near a socket.** The spec
requires that *"the Notification Service must never communicate directly with
clients"* and that *"all delivery should use the existing event infrastructure"*.
So this service persists a notification and then **publishes**
``notification.created`` on the recipient's own ``user:<id>`` topic — which the
connection manager already knows how to route and already authorizes, since a
user topic is identity equality. It holds an ``EventPublisher``, which has one
method and no way to reach a subscriber, a connection, or a client.

**Nothing here can fail a business operation.** Every path that runs on the
subscriber's thread catches its own exceptions, logs them, and counts them: the
change that produced the event committed long before this ran, so raising would
turn a successful upload into a 500 and invite a duplicating retry. That is the
same contract :meth:`~services.timeline.TimelineService.record` keeps and the
same one :meth:`~services.events.EventDispatcher.publish` keeps, applied one
layer further out.

**No notification content ever reaches a log.** There is none to reach one: a row
stores a rule key and a bounded context, and the logs here carry identifiers,
counts, rule keys, and categories only — never a rendered message, never a case
number, never a recipient's name. The same line ``code-standards.md`` draws for
OCR text, chunks, questions, answers, and report sections.
"""

